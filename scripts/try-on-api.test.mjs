import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { Readable } from 'node:stream';
import sharp from 'sharp';
import { wardrobeTryOnApi } from './try-on-api.mjs';
test('try-on sends identity and garments, deduplicates, caches, and validates', async t => {
 const dir=await mkdtemp(path.join(tmpdir(),'try-on-test-'));
 const oldFetch=globalThis.fetch;
 t.after(async()=>{globalThis.fetch=oldFetch;await rm(dir,{recursive:true,force:true});});
 await mkdir(path.join(dir,'imported'));
 const photo=await sharp({create:{width:10,height:12,channels:3,background:'#123456'}}).png().toBuffer();
 await writeFile(path.join(dir,'reference.png'),photo);
 await writeFile(path.join(dir,'imported','top.png'),photo);
 await writeFile(path.join(dir,'library.json'),JSON.stringify([{id:'top',name:'T-shirt',part:'upperbody',image:'/api/import/library/top.png'}]));
 const env={OPENAI_API_KEY:'test-only',WARDROBE_DATA_DIR:dir,WARDROBE_MODEL_REFERENCE:path.join(dir,'reference.png')};
 const plugin=wardrobeTryOnApi({env});plugin.configResolved({root:dir});let handler;plugin.configureServer({middlewares:{use(fn){handler=fn;}}});
 const call=async input=>{let result;const req=Readable.from([JSON.stringify(input)]);Object.assign(req,{url:'/api/outfits/try-on',method:'POST'});const res={statusCode:200,setHeader(){},end(value){result={status:this.statusCode,...JSON.parse(value)};}};await handler(req,res,()=>{});return result;};
 let calls=0;
 globalThis.fetch=async (url,options)=>{calls++;assert.equal(url,'https://api.openai.com/v1/images/edits');assert.equal(options.body.getAll('image[]').length,2);assert.equal(options.body.get('model'),'gpt-image-2');assert.match(options.body.get('prompt'),/identity reference/);await new Promise(r=>setTimeout(r,20));return new Response(JSON.stringify({data:[{b64_json:photo.toString('base64')}]}));};
 assert.equal((await call({itemIds:['missing']})).status,404);
 assert.equal((await call({itemIds:['top','top']})).status,400);
 const results=await Promise.all([call({itemIds:['top']}),call({itemIds:['top']})]);
 assert.equal(calls,1);assert.equal(results[0].status,200);assert.match(results[0].imageDataUrl,/^data:image\/png;base64,/);
 await call({itemIds:['top']});assert.equal(calls,1);
 env.OPENAI_IMAGE_QUALITY='medium';globalThis.fetch=async()=>new Response('{}',{status:401});
 assert.equal((await call({itemIds:['top']})).status,502);
 env.OPENAI_API_KEY=' ';assert.equal((await call({itemIds:['top']})).status,503);
 env.OPENAI_API_KEY='test-only';env.WARDROBE_MODEL_REFERENCE='missing.png';assert.equal((await call({itemIds:['top']})).status,503);
});
